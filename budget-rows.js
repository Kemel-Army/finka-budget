    function norm(s) {
        return String(s || "")
            .toLowerCase()
            .replace(/[^а-яёa-z0-9]+/g, " ")
            .trim();
    }

    /* Сначала — совпадение с типовым списком по началу наименования:
       оно точнее. Ключевые слова остаются на случай, когда в книге
       статья названа по-своему. */
    function codeFor(name) {
        var target = norm(name);
        if (!target) return "";

        var best = "";
        var bestLen = 0;
        Object.keys(SETS).forEach(function (set) {
            SETS[set].forEach(function (r) {
                var a = norm(r.name);
                if (!a) return;
                if (target.indexOf(a) !== 0 && a.indexOf(target) !== 0) return;
                var len = Math.min(a.length, target.length);
                if (len > bestLen) {
                    bestLen = len;
                    best = r.code;
                }
            });
        });
        if (bestLen >= 8) return best;

        for (var i = 0; i < ALIASES.length; i++) {
            if (ALIASES[i].test.test(target)) return ALIASES[i].code;
        }
        return "";
    }

